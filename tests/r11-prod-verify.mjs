import { chromium, devices } from 'playwright';
import fs from 'node:fs';
import path from 'node:path';
const OUT = path.resolve('tests/audit-runs/r11-postdeploy');
fs.mkdirSync(OUT, { recursive: true });
const browser = await chromium.launch({ headless: true });
const ctx = await browser.newContext({ ...devices['iPhone 14 Pro'], ignoreHTTPSErrors: true });
const page = await ctx.newPage();
await page.goto('https://punchlist.ca/', { waitUntil: 'networkidle' });
await page.waitForTimeout(2000);
await page.screenshot({ path: path.join(OUT, '01_hero.png') });
await page.evaluate(() => document.querySelector('.ln-hero-card')?.scrollIntoView({ block: 'center' }));
await page.waitForTimeout(700);
await page.screenshot({ path: path.join(OUT, '02_hero-card.png') });
await page.evaluate(() => document.querySelector('.ln-foreman-card')?.scrollIntoView({ block: 'center' }));
await page.waitForTimeout(700);
await page.screenshot({ path: path.join(OUT, '03_foreman.png') });
await browser.close();
console.log('Done');
